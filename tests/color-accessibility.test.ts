import { describe, expect, it } from "vitest";
import {
  adjustForAccessibility,
  findAccessibleColors,
} from "@/lib/utils/color/contrast-checker";
import {
  getColorInfo,
  getLuminance,
} from "@/lib/utils/color/color-converter";

describe("color accessibility foundations", () => {
  it("parses the HSL colors generated by accessibility helpers", () => {
    expect(getColorInfo("hsl(210, 100%, 50%)")).toMatchObject({
      hex: "#0080FF",
      rgb: { r: 0, g: 128, b: 255 },
    });
    expect(getColorInfo("hsl(-120deg, 100%, 50%)")?.hex).toBe("#0000FF");
  });

  it("rejects out-of-range HSL components", () => {
    expect(getColorInfo("hsl(0, 101%, 50%)")).toBeNull();
    expect(getColorInfo("hsl(0, 50%, -1%)")).toBeNull();
  });

  it("uses the WCAG 2.2 sRGB linearization breakpoint", () => {
    const channel = 0.04 * 255;
    expect(getLuminance(channel, channel, channel)).toBeCloseTo(0.04 / 12.92, 10);
  });

  it("returns actual accessible suggestions instead of silently dropping HSL", () => {
    const suggestions = findAccessibleColors("#ffffff", "AA", "normal");
    expect(suggestions.length).toBeGreaterThan(0);
    expect(suggestions).toContain("#000000");
    expect(adjustForAccessibility("#777777", "#ffffff", "AAA")).toMatch(/^#[0-9A-F]{6}$/);
  });
});
